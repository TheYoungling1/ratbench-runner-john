"""Task 8 — end-to-end orchestrator (``build.py``).

``build_dep_graph`` wires the pipeline (scan -> map -> resolve -> seed -> install
-> probe -> certify) over a tiny fixture repo, driven entirely by a
``FakeExecutor`` (no Docker/network/uv).  The canned outputs below model a repo
that imports ``cv2`` (needs libGL.so.1), ``PIL`` (clean), and ``psycopg2`` (build
fails: pg_config missing), so the run exercises every node type:
Test / Import / Package / SystemLib / Tool.

Resolution is HOST-side and install/probe/certify are CONTAINER-side; the unit
test injects the SAME ``FakeExecutor`` for both (``host_executor=`` kwarg).

Native gaps here surface as fresh ``discovered_by=PROBE`` nodes (soname/tool-
name keyed): this fixture's closure is ``uv pip compile``-style text (no
``build_from_source`` signal), so all packages have unknown build mode (None).
``seed_wheel_oracle_prior`` (construction-enrichment cluster 1a) seeds
``tool:build-essential`` for these unknowns; specific ``-dev`` headers remain
undeclared and surface as fresh PROBE nodes (soname/tool-name keyed). See
``test_build_native_gaps_are_fresh_probe_nodes_without_a_prior`` for the
documented coverage tradeoff.
"""

from __future__ import annotations

from python_deps.depgraph.build import build_dep_graph
from python_deps.depgraph.executor import CommandResult
from python_deps.depgraph.ids import (
    TEST_NODE_ID,
    binary_id,
    import_id,
    package_id,
    syslib_id,
    tool_id,
)
from python_deps.depgraph.schema import DiscoveredBy, NodeType, State

CANNED_CLOSURE = """\
# This file was autogenerated by uv via the following command:
#    uv pip compile - --python-version 3.11
numpy==1.26.4
    # via opencv-python
opencv-python==4.9.0.80
    # via -r -
Pillow==10.3.0
    # via -r -
psycopg2==2.9.9
    # via -r -
"""

INSTALL_STDERR = (
    "Building wheel for psycopg2 (setup.py): started\n"
    "    Error: pg_config executable not found.\n"
    "Building wheel for psycopg2 (setup.py): finished with status 'error'\n"
)


def _r(returncode=0, stdout="", stderr=""):
    return CommandResult(
        command="", returncode=returncode, stdout=stdout, stderr=stderr
    )


def _make_repo(tmp_path):
    (tmp_path / "app.py").write_text(
        "import os\nimport cv2\nfrom PIL import Image\nimport psycopg2\n"
    )
    # Roots are manifest-declared only (imports never generate roots), so the
    # deps this repo needs must be declared for the closure to resolve.
    (tmp_path / "pyproject.toml").write_text(
        '[project]\nname="fx"\nversion="0"\n'
        'dependencies=["opencv-python","Pillow","psycopg2"]\n'
    )
    return str(tmp_path)


def _make_executor():
    from conftest import FakeExecutor  # type: ignore

    return FakeExecutor(
        responses={
            "uv pip compile": _r(stdout=CANNED_CLOSURE),
            "pip install": _r(returncode=1, stderr=INSTALL_STDERR),
            # Stage 4a certified relink: the CONTAINER's packages_distributions()
            # is the SOLE Import->Package source now that the provisional Stage 3a
            # heuristic is retired. Honest post-install map: cv2/PIL/numpy are
            # installed and reported; psycopg2 FAILED to build (see INSTALL_STDERR)
            # so it is absent here -> its import is honestly flagged unresolved.
            "packages_distributions": _r(
                stdout='{"cv2": ["opencv-python"], "PIL": ["Pillow"], "numpy": ["numpy"]}'
            ),
            # import probes (also reused by certification of the import nodes)
            "import cv2": _r(
                returncode=1,
                stderr="ImportError: libGL.so.1: cannot open shared object file",
            ),
            "import PIL": _r(returncode=0),
            "import psycopg2": _r(
                returncode=1, stderr="ModuleNotFoundError: No module named 'psycopg2'"
            ),
            "import numpy": _r(returncode=0),
            # package certification
            "pip show opencv-python": _r(returncode=0),
            "pip show numpy": _r(returncode=0),
            "pip show Pillow": _r(returncode=0),
            "pip show psycopg2": _r(returncode=1, stderr="WARNING: Package(s) not found"),
            # system / toolchain certification
            "ldconfig": _r(returncode=1),
            "command -v pg_config": _r(returncode=1),
            # goal
            "pytest": _r(returncode=1, stderr="tests failed"),
        }
    )


def _build(tmp_path):
    ex = _make_executor()
    return build_dep_graph(_make_repo(tmp_path), ex, host_executor=ex)


def test_build_produces_all_node_types(tmp_path):
    graph = _build(tmp_path)

    # Test goal node.
    assert graph.get(TEST_NODE_ID) is not None
    # Imports (stdlib ``os`` excluded).
    for name in ("cv2", "PIL", "psycopg2"):
        assert graph.get(import_id(name)) is not None
    assert graph.get(import_id("os")) is None
    # Packages from the resolver.
    assert graph.get(package_id("opencv-python", "4.9.0.80")) is not None
    assert graph.get(package_id("numpy", "1.26.4")) is not None
    assert graph.get(package_id("Pillow", "10.3.0")) is not None
    assert graph.get(package_id("psycopg2", "2.9.9")) is not None
    # SystemLib + Tool — no RESOLVER prediction to reconcile into (no curated
    # table, no build_from_source signal in this fixture), so the observed
    # gaps surface as FRESH PROBE nodes, keyed by soname/tool name.
    assert graph.get(syslib_id("libGL.so.1")) is not None
    assert graph.get(binary_id("pg_config")) is not None
    assert graph.get(syslib_id("libgl1")) is None
    assert graph.get(tool_id("libpq-dev")) is None


def test_build_discovers_subprocess_cli_tools(tmp_path):
    """Finding C: an external tool the repo shells out to (adb) becomes a Tool
    node with an apt fix — even though it is neither a linked library (ldd) nor a
    pip build tool. Wired via Stage 3a'' (subprocess_scan)."""
    (tmp_path / "app.py").write_text(
        "import cv2\nimport subprocess\nsubprocess.run(['adb', 'devices'])\n"
    )
    ex = _make_executor()
    ex.responses["command -v adb"] = _r(returncode=1)  # absent on the slim base
    graph = build_dep_graph(str(tmp_path), ex, host_executor=ex)

    adb = graph.get(tool_id("adb"))
    assert adb is not None and adb.type is NodeType.TOOL
    assert adb.chosen_fix == "apt:adb"
    assert adb.discovered_by is DiscoveredBy.STATIC_SCAN
    assert adb.state is State.MISSING           # command -v adb -> rc1
    # hung off the Project anchor (the repo's own code invokes it)
    from python_deps.depgraph.ids import project_id
    assert any(e.dst == tool_id("adb") and e.src == project_id(tmp_path.name)
               for e in graph.edges)


def test_build_requires_topology(tmp_path):
    graph = _build(tmp_path)

    edges = {(e.src, e.dst) for e in graph.edges}
    # Test -> Imports
    assert (TEST_NODE_ID, import_id("cv2")) in edges
    assert (TEST_NODE_ID, import_id("psycopg2")) in edges
    # Import -> Package
    assert (import_id("cv2"), package_id("opencv-python", "4.9.0.80")) in edges
    assert (import_id("PIL"), package_id("Pillow", "10.3.0")) in edges
    # Package -> Package (transitive, from uv annotation)
    assert (
        package_id("opencv-python", "4.9.0.80"),
        package_id("numpy", "1.26.4"),
    ) in edges
    # Package -> SystemLib / Tool (fresh PROBE discovery, no prior to reconcile into)
    assert (
        package_id("opencv-python", "4.9.0.80"),
        syslib_id("libGL.so.1"),
    ) in edges
    assert (package_id("psycopg2", "2.9.9"), binary_id("pg_config")) in edges


