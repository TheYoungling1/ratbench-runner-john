def test_build_native_gaps_are_fresh_probe_nodes_without_a_prior(tmp_path):
    """No curated table and no build_from_source signal in this fixture ->
    seed_wheel_oracle_prior predicts only the generic build-essential toolchain,
    not specific ``-dev`` headers. The observed native gaps (libGL, libpq-dev)
    have no RESOLVER prediction and surface as fresh discovered_by=PROBE nodes
    (the design's documented coverage tradeoff — Risk #2 in the construction-
    enrichment design)."""
    graph = _build(tmp_path)

    libgl = graph.get(syslib_id("libGL.so.1"))
    pg_config = graph.get(binary_id("pg_config"))
    assert libgl.discovered_by is DiscoveredBy.PROBE
    assert pg_config.discovered_by is DiscoveredBy.PROBE
    assert libgl.check_command == "ldconfig -p | grep libGL.so.1"
    assert pg_config.check_command == "command -v pg_config"
    assert libgl.fix_candidates == ("apt:libgl1",)        # os_resolver.PROVIDER_TABLE still resolves it
    assert pg_config.fix_candidates == ("apt:libpq-dev",)  # os_resolver.PROVIDER_TABLE still resolves it
    assert any(a.outcome == "failed" for a in libgl.attempts)


