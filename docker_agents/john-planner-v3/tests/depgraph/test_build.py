_LDD_CLOSURE = """\
numpy==1.26.4
    # via opencv-python
opencv-python==4.9.0.80
    # via -r -
"""

_CV2_SO_BUILD = (
    "/usr/local/lib/python3.11/dist-packages/cv2/cv2.cpython-311-x86_64-linux-gnu.so"
)


def test_build_ldd_probe_creates_fresh_node_without_a_prior(tmp_path):
    """Stage 4.5 is LIVE in the pipeline: when install AND import both succeed,
    ldd_probe discovers ``libGL.so.1`` from the installed binary. This
    fixture's closure carries no ``build_from_source`` signal, so
    ``seed_wheel_oracle_prior`` predicts nothing here and there is no RESOLVER
    node to reconcile into — ldd_probe creates a FRESH ``discovered_by=PROBE``
    node (soname-keyed id, apt-resolved fix-candidate via os_resolver.PROVIDER_TABLE).
    (Declaration mining, which would restore reconciliation for a repo that
    DOES declare its apt deps, is cluster 1b — deferred, not part of this
    plan.)"""
    import json

    from conftest import FakeExecutor  # type: ignore

    (tmp_path / "app.py").write_text("import cv2\n")
    # Declared-only roots: opencv-python must be declared for the closure to
    # resolve (the cv2 import audits demand but never generates a root).
    (tmp_path / "pyproject.toml").write_text(
        '[project]\nname="fx"\nversion="0"\ndependencies=["opencv-python"]\n'
    )
    ex = FakeExecutor(
        responses={
            "uv pip compile": _r(stdout=_LDD_CLOSURE),
            "pip install": _r(returncode=0),  # install SUCCEEDS
            "locate_file": _r(stdout=json.dumps({"opencv-python": [_CV2_SO_BUILD]})),
            "ldd ": _r(stdout=f"{_CV2_SO_BUILD}:\n\tlibGL.so.1 => not found\n"),
            "apt-cache show libgl1": _r(stdout="Package: libgl1\n"),
        },
        default=_r(returncode=0),
    )

    graph = build_dep_graph(
        str(tmp_path), ex, host_executor=ex, exclude_newer="2024-01-01"
    )

    assert any(c.startswith("ldd ") for c in ex.calls)

    libgl = graph.get(syslib_id("libGL.so.1"))
    assert libgl is not None
    assert libgl.discovered_by is DiscoveredBy.PROBE  # no prior to reconcile into
    assert graph.get(syslib_id("libgl1")) is None       # no apt-keyed prediction exists
    assert libgl.check_command == "ldconfig -p | grep libGL.so.1"
    assert libgl.fix_candidates == ("apt:libgl1",)
    assert (
        package_id("opencv-python", "4.9.0.80"),
        syslib_id("libGL.so.1"),
    ) in {(e.src, e.dst) for e in graph.edges}


def test_build_invokes_certified_relink_stage(tmp_path):
    """Stage 4a is wired: build runs the packages_distributions probe in the
    container, and it runs BEFORE the import probe."""
    from conftest import FakeExecutor  # type: ignore

    (tmp_path / "app.py").write_text("import dateutil\n")
    # Permissive executor: every command 'succeeds' with empty output, so the
    # pipeline runs end-to-end without crashing and we can inspect .calls.
    executor = FakeExecutor(default=_r(returncode=0))

    build_dep_graph(str(tmp_path), executor, host_executor=executor, target_python="3.11")

    relink_calls = [i for i, c in enumerate(executor.calls) if "packages_distributions" in c]
    assert relink_calls, "build_dep_graph must invoke the Stage 4a relink probe"
    relink_idx = relink_calls[0]
    import_idx = next(
        (i for i, c in enumerate(executor.calls) if 'python -c "import dateutil"' in c),
        10**9,
    )
    # Stage 4a must run before the import probe so its certified edges exist when
    # import_probe attributes gaps to owning packages.
    assert relink_idx < import_idx


def test_no_provisional_3a_link_in_build(tmp_path):
    """The provisional Stage 3a ``link_imports_to_packages`` heuristic is retired:
    certified edges (Stage 4a) are the SOLE Import->Package source in a build.

    Distinguishes the two by edge ``origin``: the Stage 3a heuristic tagged its
    edges ``origin="reconcile"``; Stage 4a tags certified edges ``origin=
    "certified"``. After removing 3a, EVERY Import->Package edge a build produces
    must be ``certified`` and NONE may be ``reconcile`` — the honest proof that
    the heuristic never ran during construction (asserting only "no 3a call"
    would pass vacuously; asserting the marker actually distinguishes them)."""
    from python_deps.depgraph.schema import EdgeType

    graph = _build(tmp_path)

    imp_pkg_edges = [
        e
        for e in graph.edges
        if e.relation is EdgeType.REQUIRES
        and (s := graph.get(e.src)) is not None
        and s.type is NodeType.IMPORT
        and (d := graph.get(e.dst)) is not None
        and d.type is NodeType.PACKAGE
    ]
    # The honest fixture map certifies cv2->opencv-python and PIL->Pillow.
    assert imp_pkg_edges, "expected certified Import->Package edges from Stage 4a"
    assert all(e.origin == "certified" for e in imp_pkg_edges)
    # The retired Stage 3a heuristic marker must never appear.
    assert not any(e.origin == "reconcile" for e in imp_pkg_edges)


