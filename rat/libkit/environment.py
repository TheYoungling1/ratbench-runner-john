            def get_returncode(self):
                echo_returncode = """echo $?"""
                self.env.shell.sendline(echo_returncode)
                self.env.shell.expect([r"root@.*:.*# "], timeout=600)
                # Get output before the matched prompt from shell.before.
                output = self.env.shell.before.decode("utf-8").strip()
                output = output.replace("\x1b[?2004l\r", "")

