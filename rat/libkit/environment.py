    def build_image(self):
        """
        Build the Docker image.

        If use_repo_dockerfile=True and the repository contains a Dockerfile, use
        the repository Dockerfile; otherwise use the system-generated Dockerfile.

        Returns:
            tuple: (success: bool, used_repo_dockerfile: bool)
                   - success: whether the build succeeded
                   - used_repo_dockerfile: whether the repo Dockerfile was used
        """
        # Check whether to use the repo-provided Dockerfile.
        if (
            self.use_repo_dockerfile
            and self.repo_dockerfile_path
            and os.path.exists(self.repo_dockerfile_path)
        ):
            print(
                f"🐳 Using repo Dockerfile: {os.path.relpath(self.repo_dockerfile_path, self.root_path)}"
            )

            # Determine build context (directory containing the Dockerfile).
            build_context = os.path.dirname(self.repo_dockerfile_path)
            dockerfile_name = os.path.basename(self.repo_dockerfile_path)

            # Use the repo name as the image tag.
            image_tag = f"repo_{self.get_standard_container_name()}"
            self.namespace = image_tag

            print(f"📋 Build context: {build_context}")
            print(f"📋 Dockerfile: {dockerfile_name}")

            try:
                print(f"📋 Building image: {self.namespace}")

                # Build command.
                if dockerfile_name == "Dockerfile":
                    # Standard Dockerfile.
                    cmd = ["docker", "build", ".", "-t", self.namespace]
                else:
                    # Non-standard Dockerfile name (e.g. proxy.Dockerfile).
                    cmd = [
                        "docker",
                        "build",
                        ".",
                        "-f",
                        dockerfile_name,
                        "-t",
                        self.namespace,
                    ]

                subprocess.run(
                    cmd,
                    cwd=build_context,
                    check=True,
                )
                print(f"✅ Image built successfully: {self.namespace}")
                return True, True
            except subprocess.CalledProcessError as e:
                print(f"❌ Repo Dockerfile build failed: {e}")
                print("⚠️  Falling back to the system-generated Dockerfile")
                # Fallback marker: no longer use the repo Dockerfile.
                self.use_repo_dockerfile = False
                self.repo_dockerfile_path = None
                # Continue and try the system-generated Dockerfile.

        # Use the system-generated Dockerfile.
        if self.use_repo_dockerfile:
            print(
                "⚠️  Dockerfile not found in repo; using the system-generated Dockerfile"
            )
        print("🐳 Using system-generated Dockerfile")

        # Preserve original namespace for fallback.
        original_namespace = self.namespace
        build_context = self.create_dockerfile()
        dockerfile_name = "Dockerfile"
        self.namespace = "build_env_" + self.namespace

        try:
            print(f"📋 Building image: {self.namespace}")

            # Build command.
            cmd = ["docker", "build", ".", "-t", self.namespace]

            subprocess.run(
                cmd,
                cwd=build_context,
                check=True,
            )
            print(f"✅ Image built successfully: {self.namespace}")
            return True, False
        except subprocess.CalledProcessError as e:
            print(f"❌ Image build failed: {e}")
            print(
                f"⚠️  The recommended base image '{original_namespace}' failed to build"
            )

            # Try falling back to the default image.
            from libkit.command import get_default_namespace

            default_namespace = get_default_namespace(self.language)

            if original_namespace != default_namespace:
                print(f"🔄 Trying default base image: {default_namespace}")
                self.namespace = default_namespace

                # Regenerate Dockerfile.
                build_context = self.create_dockerfile()
                self.namespace = "build_env_" + self.namespace

                try:
                    print(f"📋 Building image: {self.namespace}")
                    cmd = ["docker", "build", ".", "-t", self.namespace]
                    subprocess.run(
                        cmd,
                        cwd=build_context,
                        check=True,
                    )
                    print(f"✅ Built successfully with default image: {self.namespace}")
                    return True, False
                except subprocess.CalledProcessError as fallback_error:
                    print(f"❌ Default image build also failed: {fallback_error}")
                    return False, False
            else:
                print("❌ Already using the default image; cannot fall back further")
                return False, False

    def _cleanup_existing_container(self, container_name):
        """Clean up any existing container with the same name."""
        try:
            # Check for an existing container with the same name.
            existing_container = None
            for container in self.client.containers.list(all=True):
                if container.name == container_name:
                    existing_container = container
                    break

            if existing_container:
                print(
                    f"⚠️ Found existing container with same name: {container_name} ({existing_container.short_id})"
                )
                if existing_container.status == "running":
                    print("🛑 Stopping running container...")
                    existing_container.stop()
                print("🗑️ Removing container...")
                existing_container.remove()
                print("✅ Cleaned up container with same name")
                return True
        except Exception as e:
            print(f"⚠️ Error cleaning up container with same name: {e}")
        return False

    def create_container(self, base_image=False):
        """
        Initialize a container.

        Returns:
            bool: whether the repo Dockerfile was used (for prompt selection)
        """
        print("🔍 Starting container creation")
        used_repo_dockerfile = False
        if not base_image:
            success, used_repo_dockerfile = self.build_image()
            if not success:
                raise Exception("Build image error!")
        image = f"{self.namespace}"
        host_path = "/tmp/patch"
        container_path = "/tmp/patch"

        # Clean up any existing container with the same name to avoid conflicts.
        self._cleanup_existing_container(self.container_name)

        try:
            # Configure environment variables to use mirror endpoints.
            environment = {
                # HuggingFace mirror configuration
                "HF_ENDPOINT": "https://hf-mirror.com",
                "HUGGINGFACE_HUB_CACHE": "/root/.cache/huggingface",
                # ModelScope mirror configuration
                "MODELSCOPE_CACHE": "/root/.cache/modelscope",
            }

            self.container = self.client.containers.run(
                image,
                command="/bin/bash",
                name=self.container_name,
                detach=True,
                tty=True,
                stdin_open=True,
                privileged=True,
                volumes={host_path: {"bind": container_path, "mode": "rw"}},
                environment=environment,
            )
            print(
                f"Container {self.container.name} {self.container.short_id} started with image {image}"
            )
            current_file_path = os.path.abspath(__file__)
            current_directory = os.path.dirname(current_file_path)
            project_directory = os.path.dirname(current_directory)
            cmd = f"chmod -R 777 {project_directory}/libkit/tools && docker cp {project_directory}/libkit/tools {self.container.name}:/home"
            print("📋 Running command:", cmd)
            subprocess.run(cmd, check=True, shell=True)
            cmd = f"docker cp {self.root_path}/input/repo/{self.full_name}/. {self.container.name}:/repo"
            print("📋 Running command:", cmd)
            subprocess.run(cmd, check=True, shell=True)
            return used_repo_dockerfile
        except Exception as e:
            print(f"Container start faild: {e}")
            return False

    def stop_container(self):
        if self.container:
            # 1. Clean up the shell first (use try/except to keep going on failure).
            if self.shell:
                try:
                    if self.shell.isalive():
                        self.shell.close(force=True)
                except Exception as e:
                    print(
                        f"⚠️  Error closing shell (will continue container cleanup): {e}"
                    )
                finally:
                    self.shell = None

            # 2. Save state based on save_mode.
            try:
                if self.save_mode == "dockerfile":
                    self.generate_final_dockerfile()
                    print(
                        f"✅ Dockerfile and test files saved to: {self.root_path}/output/{self.full_name}/"
                    )
                elif self.save_mode == "image":
                    self.save_as_image()
                    print(
                        f"✅ Container saved as image: {self.get_standard_container_name()}:final"
                    )
            except Exception as e:
                print(f"⚠️  Error saving container state (will continue cleanup): {e}")

            # 3. Stop and remove the container (use try/except for cleanup).
            try:
                self.container.stop()
                self.container.remove()
                print(f"Container {self.container.short_id} stopped and removed")
            except Exception as e:
                print(f"⚠️  Error stopping/removing container: {e}")
                # Try force remove.
                try:
                    self.container.remove(force=True)
                    print(f"Container {self.container.short_id} force removed")
                except Exception as e2:
                    print(f"❌ Force remove also failed: {e2}")
            finally:
                self.container = None

            # 4. Clean up temporary images.
            try:
                if self.save_mode == "none":
                    # Use DEVNULL instead of PIPE to avoid file descriptor leaks.
                    subprocess.run(
                        f"docker rmi {self.get_standard_container_name()}:tmp",
                        shell=True,
                        stdout=subprocess.DEVNULL,
                        stderr=subprocess.DEVNULL,
                    )
                elif self.save_mode != "image":
                    # Also delete temporary images in dockerfile mode.
                    subprocess.run(
                        f"docker rmi {self.get_standard_container_name()}:tmp",
                        shell=True,
                        stdout=subprocess.DEVNULL,
                        stderr=subprocess.DEVNULL,
                    )
            except Exception as e:
                print(f"⚠️  Error cleaning temporary image (can be ignored): {e}")

            # 5. Close the Docker client to release file descriptors.
            try:
                if self.client:
                    self.client.close()
                    self.client = None
            except Exception as e:
                print(f"⚠️  Error closing Docker client (can be ignored): {e}")

        return self.commands

