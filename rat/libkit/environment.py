def truncate_msg(result_message, command, truncate=2000, bar_truncate=20):
    lines = result_message.splitlines()
    lines = [x for x in lines if len(x.strip()) > 0]
    # Stores line indices that look like progress bars.
    bar_lines = list()
    for i in range(len(lines)):
        line = lines[i]
        if (
            line.strip().startswith("\x1b[")
            or line.count("\x1b[") >= 2
            or line.count("█") >= 2
            or "━━━━━" in line
        ):
            bar_lines.append(i)
    if len(bar_lines) > bar_truncate:
        for i in range(len(lines)):
            if i in bar_lines[:-bar_truncate]:
                lines[i] = ""
    lines = [x for x in lines if len(x) > 0]

    result_message = "\n".join(lines)
    res = result_message
    # Handle overly long output.
    if len(result_message) > truncate * 3:
        res = f"Running `{command}`...\nThe output is too long, so we've truncated it to show you the first and last 5000 characters.\n"
        res += (
            result_message[: truncate * 3]
            + "\n...[Truncation]...\n"
            + result_message[-truncate * 3 :]
        )
    elif len(result_message.split(" ")) > truncate:
        res = f"Running `{command}`...\nThe output is too long, so we've truncated it to show you the first and last 2500 words.\n"
        res += (
            " ".join(result_message.split(" ")[:truncate])
            + "\n...[Truncation]...\n"
            + " ".join(result_message.split(" ")[-truncate:])
        )

    return res


def delete_dangling_image():
    dangling_images = (
        subprocess.check_output('docker images --filter "dangling=true" -q', shell=True)
        .decode("utf-8")
        .strip()
    )
    if dangling_images:
        rmi_cmd = f"docker rmi {dangling_images}"
        # print("📋 Running command:", rmi_cmd)
        # Use DEVNULL instead of PIPE to avoid file descriptor leaks.
        subprocess.run(
            rmi_cmd, shell=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL
        )


def compare_versions(version1, version2):
    parts1 = version1.split(".")
    parts2 = version2.split(".")
    max_len = max(len(parts1), len(parts2))
    parts1.extend(["0"] * (max_len - len(parts1)))
    parts2.extend(["0"] * (max_len - len(parts2)))
    for part1, part2 in zip(parts1, parts2):
        part1 = int(part1)
        part2 = int(part2)
        if part1 > part2:
            return 1
        elif part1 < part2:
            return -1
    # If all parts are equal, the versions are the same.
    return 0


class Env:
    def __init__(
        self,
        namespace,
        language,
        repo_full_name,
        root_path,
        save_mode="none",
        use_repo_dockerfile=False,
        repo_dockerfile_path=None,
        dockerfile_content=None,
        use_uv=False,
    ):
        """
        namespace: e.g. a base image tag like python:3.11
        save_mode: 'none' - do not save; 'dockerfile' - save Dockerfile and files; 'image' - save as an image
        use_repo_dockerfile: whether to use the repository's own Dockerfile
        repo_dockerfile_path: absolute path to the repo Dockerfile (when using the repo Dockerfile)
        dockerfile_content: Dockerfile content generated by SetupAgent (optional)
        use_uv: whether to use uv as the Python package manager
        language_config: language configuration object used to generate Dockerfile
        """

        self.namespace = namespace
        self.client = docker.from_env(timeout=600)
        self.container = None
        self.shell = None
        self.commands = list()
        self.full_name = repo_full_name
        self.root_path = root_path
        self.save_mode = save_mode
        self.use_repo_dockerfile = use_repo_dockerfile
        self.repo_dockerfile_path = repo_dockerfile_path
        self.dockerfile_content = dockerfile_content

        self.use_uv = use_uv
        self.language = language

        # Language config: always fetch via get_language_config.
        # For Java, create_dockerfile updates the config dynamically based on project files.
        self.language_config = get_language_config(self.language, use_uv=self.use_uv)

        # Generate a unique container name to support parallel execution.
        self.container_name = self._generate_unique_container_name()

    def __enter__(self):
        """Context manager entry."""
        return self

    def __exit__(self, exc_type, exc_val, exc_tb):
        """Context manager exit - ensures cleanup."""
        try:
            self.stop_container()
        except Exception as e:
            print(f"⚠️  Error during context manager cleanup: {e}")
        finally:
            # Close the Docker client to release file descriptors.
            if self.client:
                try:
                    self.client.close()
                    self.client = None
                except Exception as e:
                    print(f"⚠️  Error closing Docker client: {e}")
        # Do not suppress exceptions; let them propagate.
        return False

    def get_standard_container_name(self):
        return self.full_name.lower().replace("/", "_").replace("-", "_")

    def _generate_unique_container_name(self):
        """Generate a unique container name to support parallel execution."""
        base_name = self.get_standard_container_name()
        unique_id = uuid.uuid4().hex[:8]
        return f"rat_{base_name}_{unique_id}"

    def create_shell(self):
        if self.container:
            # 1. Clean up the old shell (if any).
            if self.shell:
                try:
                    if self.shell.isalive():
                        self.shell.close(force=True)
                except Exception as e:
                    print(f"⚠️  Error closing old shell: {e}")
                finally:
                    self.shell = None

            # 2. Create a new shell.
            command = f"docker exec -it {self.container.id} /bin/bash"
            print("📋 Running command:", command)

            temp_shell = None
            try:
                # Use poll() instead of select() to avoid the >1024 file descriptor limit.
                temp_shell = pexpect.spawn(command, use_poll=True)
                # self.shell.expect([r'\$ ', r'# '], timeout=600)
                temp_shell.expect([r"[$#]"], timeout=600)

                # If using uv, ensure PATH includes uv's install path.
                if self.use_uv:
                    temp_shell.sendline('export PATH="/root/.cargo/bin:$PATH"')
                    temp_shell.expect([r"[$#]"], timeout=10)

                # 3. Only assign to self.shell after success.
                self.shell = temp_shell

            except Exception as e:
                # 4. If it fails, clean up the temporary shell.
                print(f"❌ Failed to create shell: {e}")
                if temp_shell:
                    try:
                        temp_shell.close(force=True)
                    except:
                        pass
                raise Exception(f"Failed to create shell: {e}")
        else:
            raise Exception("Container not started. Call start_container() first.")

    def recreate_shell(self, target_dir="/repo"):
        """
        Recreate the Shell session.

        When the Shell becomes unavailable (e.g. due to timeouts), close the old
        connection and create a new Shell. After recreation, it automatically
        switches to the target working directory.

        Args:
            target_dir: Directory to switch to after recreation; defaults to /repo.

        Returns:
            bool: Whether recreation succeeded.
        """
        print("🔄 Shell session unavailable; recreating...")

        try:
            # 1. Close the old shell (if any and still alive).
            if self.shell:
                try:
                    if self.shell.isalive():
                        self.shell.close(force=True)
                        print("   ✓ Closed old Shell")
                except Exception as e:
                    print(f"   ⚠️  Error closing old Shell: {e}")
                finally:
                    self.shell = None

            # 2. Create a new shell.
            self.create_shell()
            print("   ✓ Created new Shell")

            # 3. Switch to the target working directory.
            if target_dir and target_dir != "/root":
                try:
                    self.shell.sendline(f"cd {target_dir}")
                    self.shell.expect([r"root@.*:.*# ", r"[$#]"], timeout=5)
                    print(f"   ✓ Switched to directory: {target_dir}")
                except Exception as e:
                    print(f"   ⚠️  Failed to switch directory: {e}; using default")
                    # If switching fails, try /repo.
                    if target_dir != "/repo":
                        try:
                            self.shell.sendline("cd /repo")
                            self.shell.expect([r"root@.*:.*# ", r"[$#]"], timeout=5)
                            print("   ✓ Switched to /repo")
                        except:
                            print("   ⚠️  Failed to switch to /repo; keeping current")

            print("✅ Shell recreation succeeded")
            return True

        except Exception as e:
            print(f"❌ Shell recreation failed: {e}")
            return False

    def create_dockerfile(self):
        dockerfile_path = f"{self.root_path}/input/repo/{self.full_name}/Dockerfile"

        # If dockerfile_content is provided (generated by SetupAgent), use it directly.
        if self.dockerfile_content:
            print("✅ Using Dockerfile generated by SetupAgent")
            with open(dockerfile_path, "w") as f:
                f.write(self.dockerfile_content)
            return f"{self.root_path}/input/repo/{self.full_name}"

        # Fallback: generate via LanguageConfig (for non-Rust projects or when SetupAgent fails).
        print("⚠️  Falling back to LanguageConfig template for Dockerfile generation")

        # Extract version.
        parts = self.namespace.lower().strip().split(":")
        base_image = parts[0]
        version = parts[1] if len(parts) > 1 else "latest"

        # Generate Dockerfile content using the language config.
        repo_dir = f"{self.root_path}/input/repo/{self.full_name}"
        is_maven = os.path.exists(os.path.join(repo_dir, "pom.xml"))
        is_gradle = os.path.exists(os.path.join(repo_dir, "build.gradle"))

        dockerfile_content = self.language_config.get_dockerfile_content(
            base_image, version, is_maven=is_maven, is_gradle=is_gradle
        )

        with open(dockerfile_path, "w") as f:
            f.write(dockerfile_content)
        return f"{self.root_path}/input/repo/{self.full_name}"

    def commit_container(self):
        try:
            delete_dangling_image()
            image = self.container.commit(
                repository=f"{self.get_standard_container_name()}", tag="tmp"
            )
            return True
        except ContainerError as e:
            print(f"Error committing container: {e}")
            return None

    def generate_final_dockerfile(self):
        """Generate a Dockerfile containing all executed commands."""
        try:
            output_dir = f"{self.root_path}/output/{self.full_name}"
            os.makedirs(output_dir, exist_ok=True)

            # Generate Dockerfile content.
            dockerfile_lines = [f"FROM {self.namespace.replace('build_env_', '')}"]

            # Add initial configuration.
            dockerfile_lines.extend(
                [
                    "",
                    "# Configure pip",
                    "RUN mkdir -p ~/.pip && touch ~/.pip/pip.conf",
                    'RUN echo "[global]" >> ~/.pip/pip.conf && echo "[install]" >> ~/.pip/pip.conf',
                ]
            )

            # Add dependencies based on Python version.
            if (
                self.namespace.lower().strip().split(":")[0].replace("build_env_", "")
                == "python"
            ):
                python_version = (
                    self.namespace.lower().strip().split(":")[1].split("-")[0].strip()
                )
                if compare_versions(python_version, "3.8") >= 0:
                    dockerfile_lines.extend(
                        [
                            "",
                            "# Install system dependencies",
                            "RUN apt-get update && apt-get install -y curl",
                            "",
                            "# Install Poetry",
                            "RUN curl -sSL https://install.python-poetry.org | python -",
                            'ENV PATH="/root/.local/bin:$PATH"',
                            "",
                            "# Install base tools",
                            "RUN pip install pytest",
                            "RUN pip install openai -i https://mirrors.aliyun.com/pypi/simple",
                            "RUN pip install pipdeptree",
                            "",
                            "# Git config",
                            "RUN git config --global --add safe.directory /repo",
                        ]
                    )
                else:
                    dockerfile_lines.extend(
                        [
                            "",
                            "# Install system dependencies",
                            "RUN apt-get update && apt-get install -y curl",
                            "",
                            "# Install base tools",
                            "RUN pip install pytest",
                            "RUN pip install pipdeptree",
                            "",
                            "# Git config",
                            "RUN git config --global --add safe.directory /repo",
                        ]
                    )

            # Add working directory.
            dockerfile_lines.extend(
                [
                    "",
                    "# Set working directory",
                    "WORKDIR /repo",
                ]
            )
            # Extract installation commands from history.
            dockerfile_lines.append("")
            dockerfile_lines.append(
                "# Executed setup commands (generated from history)"
            )
            for cmd_info in self.commands:
                cmd = cmd_info.get("command", "")
                returncode = cmd_info.get("returncode", -1)

                # Keep only successful commands, and filter out commands unsuitable for a Dockerfile.
                if returncode == 0 and cmd.strip():
                    # Filter out unsuitable commands.
                    skip_patterns = [
                        "cd ",
                        "pwd",
                        "ls ",
                        "cat ",
                        "echo $",
                        "sleep",
                        "pytest",
                        "python -m pytest",
                    ]
                    should_skip = any(
                        cmd.strip().startswith(pattern) for pattern in skip_patterns
                    )

                    if not should_skip:
                        # For pip install, apt-get, etc., add to the Dockerfile.
                        patterns = [
                            "pip install",
                            "apt-get install",
                            "poetry install",
                            "npm install",
                        ]
                        # If using uv, include uv-related command patterns.
                        if self.use_uv:
                            patterns.extend(
                                [
                                    "uv pip install",
                                    "uv sync",
                                    "uv add",
                                    "uv pip sync",
                                ]
                            )

                        if any(pattern in cmd for pattern in patterns):
                            dockerfile_lines.append(f"RUN {cmd}")

            # Write Dockerfile.
            dockerfile_path = os.path.join(output_dir, "Dockerfile")
            with open(dockerfile_path, "w", encoding="utf-8") as f:
                f.write("\n".join(dockerfile_lines))

            # Copy test files and related config files.
            repo_path = f"{self.root_path}/input/repo/{self.full_name}"
            if os.path.exists(repo_path):
                # Copy the entire repo directory into output.
                import shutil

                dest_repo_path = os.path.join(output_dir, "repo")
                if os.path.exists(dest_repo_path):
                    shutil.rmtree(dest_repo_path)
                shutil.copytree(repo_path, dest_repo_path)

            # Generate usage documentation.
            readme_path = os.path.join(output_dir, "README.md")
            with open(readme_path, "w", encoding="utf-8") as f:
                f.write(f"""# {self.full_name} - Environment Setup

## Build Image

```bash
docker build -t {self.get_standard_container_name()}:final .
```

## Run Container

```bash
docker run -it --rm -v $(pwd)/repo:/repo {self.get_standard_container_name()}:final /bin/bash
```

## Command History

Below are the commands executed while setting up the environment:

""")
                for i, cmd_info in enumerate(self.commands, 1):
                    cmd = cmd_info.get("command", "")
                    returncode = cmd_info.get("returncode", -1)
                    status = "✅" if returncode == 0 else "❌"
                    f.write(f"{i}. {status} `{cmd}`\n")

            print(f"📝 Generated Dockerfile with {len(self.commands)} commands")
            return True

        except Exception as e:
            print(f"❌ Error generating Dockerfile: {e}")
            return False

